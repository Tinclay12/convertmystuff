import type { NextConfig } from "next";
import legacyToolRedirects from "./src/lib/seo/legacy-redirects.json" with { type: "json" };
import retiredGuideRedirects from "./src/lib/seo/retired-guide-redirects.json" with { type: "json" };

const securityHeaders = [
  { key: "X-Frame-Options", value: "SAMEORIGIN" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=()",
  },
  {
    key: "Strict-Transport-Security",
    value: "max-age=63072000; includeSubDomains; preload",
  },
];

const nextConfig: NextConfig = {
  turbopack: { root: process.cwd() },
  trailingSlash: true,
  poweredByHeader: false,
  async redirects() {
    return [
      {
        source: "/:path*",
        has: [{ type: "host", value: "www.convertmystuff.com" }],
        destination: "https://convertmystuff.com/:path*",
        permanent: true,
      },
      // Flat `/{category}/{slug}/` tool URLs predate the subcategory segment in
      // canonical paths and 404 today. Generated by `npm run seo:redirects`.
      ...legacyToolRedirects.map(({ source, destination }) => ({
        source,
        destination,
        permanent: true,
      })),
      // Stub guides retired into the longer article covering the same topic,
      // so one page per query carries the signal instead of two.
      ...retiredGuideRedirects.map(({ source, destination }) => ({
        source,
        destination,
        permanent: true,
      })),
    ];
  },
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: securityHeaders,
      },
    ];
  },
};

export default nextConfig;
